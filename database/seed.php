/**
 * Create a clean gradient placeholder (no text — GD built-in fonts break Cyrillic).
 */
function createPlaceholderImage(string $path, string $title, array $rgb): void
{
    $width = 800;
    $height = 450;
    $image = imagecreatetruecolor($width, $height);

    $r = $rgb[0];
    $g = $rgb[1];
    $b = $rgb[2];

    for ($y = 0; $y < $height; $y++) {
        $t = $y / ($height - 1);
        $color = imagecolorallocate(
            $image,
            (int) max(0, min(255, $r + (255 - $r) * $t * 0.35)),
            (int) max(0, min(255, $g + (255 - $g) * $t * 0.35)),
            (int) max(0, min(255, $b + (255 - $b) * $t * 0.35))
        );
        imageline($image, 0, $y, $width, $y, $color);
    }

    // Soft circle accent, no text
    $overlay = imagecolorallocatealpha($image, 255, 255, 255, 100);
    imagefilledellipse($image, (int) ($width * 0.75), (int) ($height * 0.3), 280, 280, $overlay);
    $overlay2 = imagecolorallocatealpha($image, 0, 0, 0, 110);
    imagefilledellipse($image, (int) ($width * 0.2), (int) ($height * 0.8), 220, 220, $overlay2);

    imagejpeg($image, $path, 88);
    imagedestroy($image);
}

$insertPost = $pdo->prepare('
    INSERT INTO posts (title, description, content, image, views, created_at)
    VALUES (:title, :description, :content, :image, :views, :created_at)
');
$insertPivot = $pdo->prepare('
    INSERT INTO post_categories (post_id, category_id) VALUES (:post_id, :category_id)
');

foreach ($posts as $index => $post) {
    $filename = 'post-' . ($index + 1) . '.jpg';
    $fullPath = $uploadsDir . '/' . $filename;
    createPlaceholderImage($fullPath, $post['title'], $post['color']);

    $createdAt = (new DateTimeImmutable('now'))
        ->modify('-' . $post['days_ago'] . ' days')
        ->modify('-' . ($index * 3) . ' hours')
        ->format('Y-m-d H:i:s');

    $insertPost->execute([
        'title' => $post['title'],
        'description' => $post['description'],
        'content' => $post['content'],
        'image' => '/uploads/' . $filename,
        'views' => $post['views'],
        'created_at' => $createdAt,
    ]);

    $postId = (int) $pdo->lastInsertId();

    foreach ($post['categories'] as $catIndex) {
        $insertPivot->execute([
            'post_id' => $postId,
            'category_id' => $categoryIds[$catIndex],
        ]);
    }

    echo "Post: {$post['title']}\n";
}

echo "Done. Seeded " . count($categories) . " categories and " . count($posts) . " posts.\n";
